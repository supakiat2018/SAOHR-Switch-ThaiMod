import csv
import struct

with open(r'extracted_switch_usa\msg\localize_msg.dat', 'rb') as f:
    sw_raw = f.read()

cnt, _ = struct.unpack_from('<II', sw_raw, 16)
keys = []
sw_d = {}
for i in range(1, cnt + 1):
    mid, roff = struct.unpack_from('<II', sw_raw, 16 + i*8)
    aoff = 16 + roff
    end = sw_raw.find(b'\x00', aoff)
    s = sw_raw[aoff:end].decode('utf-8', 'ignore').strip()
    keys.append(mid)
    sw_d[mid] = s

def clean_ctrl(s):
    # Replace control sequences like \x1110\x100... (Player Name placeholder) with <Player>
    if '\x11' in s:
        idx = s.find('\x11')
        end = s.rfind('\x10')
        if end != -1:
            s = s[:idx] + '<ชื่อผู้เล่น>' + s[end+1:]
    return s

